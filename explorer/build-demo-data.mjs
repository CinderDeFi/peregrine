/**
 * Build explorer/demo-data.json from the real Rust-generated proof fixture.
 * Everything here is a genuine proof: the offline demo verifies for real.
 *
 * Run from anywhere: `node explorer/build-demo-data.mjs`
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { tableId, toHex } from "./vendor/peregrine-sdk.js";

const dir = fileURLToPath(new URL(".", import.meta.url));
const fixture = fileURLToPath(new URL("../sdk/js/test/fixtures/proven-read.json", import.meta.url));
const out = fileURLToPath(new URL("./demo-data.json", import.meta.url));

const fx = JSON.parse(readFileSync(fixture, "utf8"));
const TICKS = toHex(tableId("sys.stream_ticks"));

function asciiOrNull(hex) {
  const b = hex.match(/../g)?.map((h) => parseInt(h, 16)) ?? [];
  if (b.length === 0 || b.some((c) => c < 0x20 || c > 0x7e)) return null;
  return String.fromCharCode(...b);
}

function describe(table, key) {
  if (table === TICKS) {
    const idx = key.length === 80 ? parseInt(key.slice(64), 16) : null;
    return { category: "stream", label: idx === null ? "stream tick" : `acme/BTC-USD · tick #${idx}` };
  }
  const s = asciiOrNull(key);
  return { category: "table", label: s ? `contract.answers['${s}']` : `table row ${key.slice(0, 8)}…` };
}

const snapshot = (v) => ({ treeVersion: v.treeVersion, storeRoot: v.storeRoot, reads: v.reads, absent: v.absent });

const catalog = [];
for (const r of fx.v1.reads) catalog.push({ table: r.table, key: r.key, ...describe(r.table, r.key) });
if (fx.v1.absent?.[0]) {
  const a = fx.v1.absent[0];
  catalog.push({ table: a.table, key: a.key, category: "table", label: `absent: '${asciiOrNull(a.key) ?? a.key}'` });
}

const data = {
  note:
    "Real proofs generated by the Rust node (sdk/js/test/fixtures/proven-read.json). " +
    "This offline demo verifies every value for real; connect a live gateway for a moving head.",
  snapshots: [snapshot(fx.v1), snapshot(fx.v2)],
  catalog,
};

writeFileSync(out, JSON.stringify(data, null, 2) + "\n");
console.log(`wrote ${out}: ${data.snapshots.length} snapshots, ${catalog.length} catalog entries`);
void dir;
